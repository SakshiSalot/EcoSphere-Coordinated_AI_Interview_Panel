"""The assessment as a document somebody can file.

PS11 capability 10 asks for a written report. A web page is not one: hiring
decisions get forwarded, argued about six weeks later, and attached to
paperwork, and none of that works with a URL behind a login that renders
whatever the database says today. A PDF is a fixed record of what was known
when the decision was made.

RENDERED SERVER-SIDE, with WeasyPrint. The alternative was a print stylesheet
and asking the operator to use their browser's Save as PDF, which produces a
different document on every machine, silently drops backgrounds by default, and
cannot be generated by anything except a human at a keyboard — no emailing it,
no attaching it to an ATS, no scripting it.

TWO RULES THIS DOCUMENT KEEPS, both inherited from the rest of the product:

  * EVERY MARK CARRIES ITS QUOTE. A number a hiring manager cannot see the
    reason for is not evidence. The quotes were verified against the transcript
    when they were scored, so nothing here can cite something unsaid.

  * WHAT WAS NOT MEASURED IS SAID OUT LOUD. A thin interview, a missing round,
    monitoring that was not running — each is printed as plainly as the score
    is. A report that only shows what it knows reads as though it knows
    everything.

The full transcript goes at the back, numbered, so every quote above can be
found in context rather than taken on trust.
"""

import html
import logging
from datetime import datetime

log = logging.getLogger("report")

